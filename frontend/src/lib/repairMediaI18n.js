export function repairMediaT(lang, key, values = {}) {
  const text = REPAIR_MEDIA_COPY[lang]?.[key] || REPAIR_MEDIA_COPY.en[key] || key;
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] == null ? match : String(values[name]));
}
