/** @param {object} o */
function modelShortName(brand, model) {
  const b = String(brand || '').trim();
  const m = String(model || '').trim();
  if (b && m.toLowerCase().startsWith(b.toLowerCase())) {
    return m.slice(b.length).trim() || m;
  }
  return m;
}

/** @param {object} o */
function entry(o) {
  const code =
    o.internalCodePrefix ||
    o.catalogKey
      .split('-')
      .map((p) => p.slice(0, 3).toUpperCase())
      .join('')
      .slice(0, 6);
  const strict = o.serialValidation === 'strict';
  const model = o.model;
  const brand = o.brand;
  return {
    catalogKey: o.catalogKey,
    brand,
    model,
    modelShort: o.modelShort || modelShortName(brand, model),
    cameraType: o.cameraType,
    serialValidation: strict ? 'strict' : 'none',
    serialPrefix: o.serialPrefix || `${code}-`,
    serialPattern: o.serialPattern || `${code}-XXXXXX`,
    serialMin: o.serialMin ?? 1,
    serialMax: o.serialMax ?? 9999999,
    yearMin: o.yearMin ?? 1950,
    yearMax: o.yearMax ?? 2010,
    internalCodePrefix: code,
    notes: o.notes || '',
  };
}

